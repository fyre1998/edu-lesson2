def result_row(item, catalogue=None):
    label, values = (catalogue or RESULTS)[item['result_id']]
    return dict(**item, label=label, **values, unit='g', source=SOURCE)


def validate_matches(result):
    if not isinstance(result, dict) or set(result) != {'readable', 'matches', 'questions', 'uncovered'}:
        raise ValueError('invalid mass result')
    if type(result['readable']) is not bool or not isinstance(result['matches'], list) or len(result['matches']) > 4:
        raise ValueError('invalid matches')
    seen = set()
    for item in result['matches']:
        if not isinstance(item, dict) or set(item) != {'result_id', 'excerpt'}:
            raise ValueError('invalid item')
        key = item['result_id']
        if not isinstance(key, str) or key not in RESULTS or key in seen or not isinstance(item['excerpt'], str) or not 1 <= len(item['excerpt'].strip()) <= 500:
            raise ValueError('invalid treatment')
        seen.add(key)
    for key, cap in [('questions', 1), ('uncovered', 6)]:
        if not isinstance(result[key], list) or len(result[key]) > cap or any(not isinstance(s, str) or not 1 <= len(s.strip()) <= 240 for s in result[key]):
            raise ValueError('invalid question')
    if not result['readable'] and (result['matches'] or not result['questions']):
        raise ValueError('unreadable')
    return result


def chat_answer(result):
    if not isinstance(result, dict) or set(result) != set(CHAT_SCHEMA['properties']):
        raise ValueError('invalid chat')
    matched = validate_matches({k: result[k] for k in MATCH_SCHEMA['properties']})
    cases = result['case_ids']
    if not isinstance(cases, list) or len(cases) > 3 or any(not isinstance(k, str) or k not in CASES for k in cases) or len(set(cases)) != len(cases):
        raise ValueError('invalid cases')
    if not isinstance(result['text'], str) or len(result['text']) > 600:
        raise ValueError('invalid text')
    sections = [f'{CASES[k][0]}\n{CASES[k][1]}' for k in cases]
    if cases:
        sections.append('来源：教师提供的《植物激素》课件第3页。请根据处理与现象归纳激素作用。')
    if matched['matches']:
        rows = [result_row(i) for i in matched['matches']]
        sections.append('对应处理的百粒质量：\n' + '\n'.join(f'{r["label"]}：{r["mass"]} ± {r["uncertainty"]} g' for r in rows))
        return '\n\n'.join(sections)
    sections.extend(matched['questions'])
    sections.extend('暂无对应课件数据：' + s for s in matched['uncovered'])
    # Numeric results always come from the fixed catalogue, never free model text.
    if not sections:
        import re
        text = result['text'].strip()
        sections.append(text if text and not re.search(r'\d|[百千]粒.*[克g]|克|±', text) else '请说明需要哪种激素的案例，或写明各实验组分别用什么处理。')
    return '\n\n'.join(sections)
